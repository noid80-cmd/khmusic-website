async function main() {
  for (const p of posts) {
    const exists = await prisma.blogPost.findUnique({ where: { slug: p.slug } });
    if (exists) {
      console.log(`건너뜀 (이미 있음): ${p.title}`);
      continue;
    }
    await prisma.blogPost.create({
      data: { ...p, status: 'DRAFT', isAutoDraft: true },
    });
    console.log(`초안 생성: ${p.title}`);
  }
  const n = await prisma.blogPost.count();
  console.log(`\n블로그 글 총 ${n}건 (초안 상태 — 관리자 화면에서 검토 후 게시)`);
  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error(e);
  await prisma.$disconnect();
  process.exit(1);
});
